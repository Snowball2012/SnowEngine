#include "StdAfx.h"

#include "AutomationBridge.h"

#include <Core/CVars.h>

#include <rapidjson/document.h>
#include <rapidjson/istreamwrapper.h>
#include <rapidjson/ostreamwrapper.h>
#include <rapidjson/prettywriter.h>

#include <filesystem>
#include <fstream>

namespace
{
    using JsonDocument = rapidjson::Document;
    using JsonValue = rapidjson::Value;

    void AddString( JsonDocument& document, JsonValue& object, const char* name, const std::string& value )
    {
        auto& allocator = document.GetAllocator();
        object.AddMember(
            JsonValue( name, allocator ),
            JsonValue( value.c_str(), static_cast<rapidjson::SizeType>( value.size() ), allocator ),
            allocator );
    }

    bool WriteResponse( const std::filesystem::path& response_path, const JsonDocument& response )
    {
        const std::filesystem::path temp_path = response_path.string() + ".tmp";
        std::ofstream stream( temp_path, std::ios::out | std::ios::trunc );
        if ( !stream.good() )
            return false;

        rapidjson::OStreamWrapper wrapper( stream );
        rapidjson::PrettyWriter<rapidjson::OStreamWrapper> writer( wrapper );
        response.Accept( writer );
        stream.flush();
        stream.close();

        std::error_code error;
        std::filesystem::rename( temp_path, response_path, error );
        if ( error )
        {
            std::filesystem::remove( temp_path );
            return false;
        }
        return true;
    }

    std::string GetStringMember( const JsonValue& object, const char* name )
    {
        const auto member = object.FindMember( name );
        if ( member == object.MemberEnd() || !member->value.IsString() )
            return {};
        return member->value.GetString();
    }
}

AutomationBridge::AutomationBridge( Console& console, const std::filesystem::path& engine_root )
    : m_console( console )
{
    const std::filesystem::path bridge_path = engine_root / ".snowengine_mcp";
    m_requests_path = bridge_path / "requests";
    m_responses_path = bridge_path / "responses";

    std::error_code error;
    std::filesystem::create_directories( m_requests_path, error );
    if ( !error )
        std::filesystem::create_directories( m_responses_path, error );

    m_ready = !error;
    if ( m_ready )
        SE_LOG_INFO( Engine, "Automation bridge ready at %s", bridge_path.string().c_str() );
    else
        SE_LOG_ERROR( Engine, "Could not initialize automation bridge at %s: %s", bridge_path.string().c_str(), error.message().c_str() );
}

void AutomationBridge::Tick()
{
    if ( !m_ready )
        return;

    std::error_code error;
    size_t processed_count = 0;
    for ( const std::filesystem::directory_entry& entry : std::filesystem::directory_iterator( m_requests_path, error ) )
    {
        if ( error || processed_count >= 16 )
            break;
        if ( !entry.is_regular_file() || entry.path().extension() != ".json" )
            continue;

        ProcessRequest( entry.path() );
        ++processed_count;
    }
}

void AutomationBridge::ProcessRequest( const std::filesystem::path& request_path )
{
    JsonDocument request;
    {
        std::ifstream stream( request_path );
        rapidjson::IStreamWrapper wrapper( stream );
        request.ParseStream( wrapper );
    }

    // The filename is generated by the MCP server and is safe to use for the
    // response path. Never trust a request JSON field as a filesystem path.
    const std::string request_id = request_path.stem().string();
    std::string method;
    if ( request.IsObject() )
    {
        method = GetStringMember( request, "method" );
    }

    JsonDocument response;
    response.SetObject();
    auto& allocator = response.GetAllocator();
    AddString( response, response, "id", request_id );
    JsonValue result( rapidjson::kObjectType );
    bool success = false;
    std::string error_message;

    const JsonValue* params = nullptr;
    if ( request.IsObject() )
    {
        const auto params_it = request.FindMember( "params" );
        if ( params_it != request.MemberEnd() && params_it->value.IsObject() )
            params = &params_it->value;
    }

    if ( request.HasParseError() || !request.IsObject() )
    {
        error_message = "Request is not valid JSON";
    }
    else if ( method == "ping" )
    {
        success = true;
        AddString( response, result, "status", "running" );
    }
    else if ( method == "execute_console_command" )
    {
        const std::string command = params ? GetStringMember( *params, "command" ) : std::string();
        if ( command.empty() )
        {
            error_message = "Parameter 'command' is required";
        }
        else
        {
            const size_t output_start = m_console.GetOutputSnapshot().size();
            success = m_console.ProcessCommand( command.c_str() );
            const std::vector<std::string> output = m_console.GetOutputSnapshot();
            JsonValue lines( rapidjson::kArrayType );
            for ( size_t i = std::min( output_start, output.size() ); i < output.size(); ++i )
                lines.PushBack( JsonValue( output[i].c_str(), allocator ), allocator );
            result.AddMember( "lines", lines, allocator );
        }
    }
    else if ( method == "get_cvar" )
    {
        const std::string name = params ? GetStringMember( *params, "name" ) : std::string();
        std::string value;
        success = !name.empty() && m_console.GetCVarValue( name.c_str(), value );
        if ( success )
        {
            AddString( response, result, "name", name );
            AddString( response, result, "value", value );
        }
        else
        {
            error_message = name.empty() ? "Parameter 'name' is required" : "Unknown CVar: " + name;
        }
    }
    else if ( method == "set_cvar" )
    {
        const std::string name = params ? GetStringMember( *params, "name" ) : std::string();
        const std::string value = params ? GetStringMember( *params, "value" ) : std::string();
        std::string output;
        success = !name.empty() && m_console.SetCVarValue( name.c_str(), value.c_str(), output );
        if ( success )
        {
            AddString( response, result, "name", name );
            AddString( response, result, "value", value );
            AddString( response, result, "message", output );
        }
        else
        {
            error_message = output.empty() ? "Parameters 'name' and 'value' are required" : output;
        }
    }
    else if ( method == "get_logs" )
    {
        size_t since = 0;
        if ( params )
        {
            const auto since_it = params->FindMember( "since" );
            if ( since_it != params->MemberEnd() && since_it->value.IsUint64() )
                since = static_cast<size_t>( since_it->value.GetUint64() );
        }

        const std::vector<std::string> output = m_console.GetOutputSnapshot();
        since = std::min( since, output.size() );
        JsonValue lines( rapidjson::kArrayType );
        for ( size_t i = since; i < output.size(); ++i )
            lines.PushBack( JsonValue( output[i].c_str(), allocator ), allocator );
        result.AddMember( "lines", lines, allocator );
        result.AddMember( "next", static_cast<uint64_t>( output.size() ), allocator );
        success = true;
    }
    else
    {
        error_message = "Unknown bridge method: " + method;
    }

    response.AddMember( "ok", success, allocator );
    response.AddMember( "result", result, allocator );
    if ( !success )
        AddString( response, response, "error", error_message );

    const std::filesystem::path response_path = m_responses_path / ( request_id + ".json" );
    if ( !WriteResponse( response_path, response ) )
        SE_LOG_ERROR( Engine, "Could not write automation response %s", response_path.string().c_str() );

    std::error_code remove_error;
    std::filesystem::remove( request_path, remove_error );
}
